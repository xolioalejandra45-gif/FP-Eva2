
package eva2_15_acumuladores;

public class Eva2_15_ACUMULADORES {

    public static void main(String[] args) {
//        Acumuladores: ++ -- += -= *= /=
            int cuenta = 0; 
            // = es una asiganción
            System.out.println(cuenta);
            cuenta = cuenta + 100; //acumulador
            System.out.println(cuenta);
            cuenta = cuenta + 1000;
            System.out.println(cuenta);
            cuenta = cuenta - 800; // cuenta -= 800 (es lo mismo)
            System.out.println(cuenta);
            cuenta += 2000;
            System.out.println(cuenta);
    }
    
}
