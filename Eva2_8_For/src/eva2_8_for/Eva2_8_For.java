package eva2_8_for;

public class Eva2_8_For {

    public static void main(String[] args) {
        int i;
//        Incremento
        for(i = 1 ; i <= 10; i++){
            System.out.println("Hola mundo");
        }
//        Decremento
        for(i = 10 ; i >= 1; i--){
            System.out.println(i);
        }
    }
    
}
